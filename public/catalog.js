/* ═══════════ פירוק טקסט מהדבקה (ייבוא וואטסאפ) ═══════════
   כל שורה = פריט. מנקה בולטים/מספור/אימוג'ים/וי, ומנסה לחלץ כמות.   */
function parseImport(text) {
  if (!text) return [];
  const lines = String(text).split(/\r?\n/);
  const items = [];
  const seen = new Set();

  for (let raw of lines) {
    let line = raw.trim();
    if (!line) continue;

    // הסרת תבליטים / מספור / סימני וי / מקפים בתחילת שורה
    line = line.replace(/^[\s\-\*•·▪◦‣✓✔☑\[\]\(\)]+/u, "");
    line = line.replace(/^\d+[\.\)\-]\s*/, ""); // "1. " "2) "
    // הסרת אימוג'ים נפוצים
    line = line.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, "");
    line = line.trim();
    if (!line) continue;

    // התעלמות משורות כותרת נפוצות
    if (/^(רשימת? קניות|קניות|לסופר|סופר|shopping ?list|grocery|to ?do)\b/i.test(line)) continue;
    if (/^(רשימה)[\s:：]/.test(line)) continue;

    // חילוץ כמות מסוף השורה:
    //   "חלב x2" / "חלב 2" / "מלפפונים 1 ק״ג" / "עגבניות 500 גרם"
    // או מתחילת השורה: "2 חלב"
    let qty = "";
    let m;
    const UNIT = "(?:ק[\"״']?ג|קג|גרם|גר['׳]?|ליטר|ל['׳]?|מ\"ל|מל|יח['׳]?|יחי['׳]?|חבילה|מארז|אריזה|בקבוק|שקית|קופסה|תבנית|כיכר)?";
    if ((m = line.match(new RegExp("[\\sxX×\\-–]\\s*(\\d+(?:\\.\\d+)?\\s*" + UNIT + ")\\s*$")))) {
      qty = m[1].trim();
      line = line.slice(0, m.index).trim();
    } else if ((m = line.match(/^(\d+(?:\.\d+)?)\s+(.+)/))) {
      qty = m[1];
      line = m[2].trim();
    }

    line = line.replace(/[\-–\s]+$/, "").trim();
    if (!line) continue;

    const key = line.toLowerCase();
    if (seen.has(key)) continue; // מניעת כפילויות בתוך הייבוא
    seen.add(key);

    items.push({
      name: line.slice(0, 120),
      qty: qty.slice(0, 40),
      price: "",
      aisle: categorize(line),
    });
  }
  return items;
}
