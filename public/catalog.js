/* נרמול: ממיר אותיות סופיות לרגילות כדי ש"מלפפון" יתאים ל"מלפפונים",
   ומסיר גרשיים/גרש כדי ש'ק"ג' יזוהה */
function normHe(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/ך/g, "כ").replace(/ם/g, "מ").replace(/ן/g, "נ")
    .replace(/ף/g, "פ").replace(/ץ/g, "צ");
}

function categorize(name) {
  if (!name) return "other";
  const n = normHe(name).trim();
  // בוחרים את ההתאמה הספציפית ביותר: מילת המפתח הארוכה ביותר שמוכלת בשם.
  // כך "פיתות" מתאים ל"פיתות" (מאפייה) ולא ל"תות" (ירקות).
  let best = null;
  let bestLen = 0;
  for (const aisle of Object.keys(CATALOG)) {
    for (const kw of CATALOG[aisle]) {
      const k = normHe(kw);
      if (k.length > bestLen && n.includes(k)) {
        best = aisle;
        bestLen = k.length;
      }
    }
  }
  return best || "other";
}

